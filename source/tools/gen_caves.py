#!/usr/bin/env python3
"""Assemble the caves with GNU as, extract the bytes, find the relocation placeholders and
emit caves.h.  Also provides assemble() for the test harness."""
import subprocess, struct, sys, os, tempfile
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
WHICH = ['A_AREA','A_STREAK','A_LGFLAG','A_ROUND','A_SCHEME','A_ARRAY',
         'A_SLOT0','A_SLOT1','A_SLOT2','A_SLOT3','A_SLOT4','A_SLOT5','A_MEP','A_NIM','A_ZAL']
PLACEHOLDERS = {name: 0xCAFE0001 + i for i, name in enumerate(WHICH)}
CAVES = (('dodger.inc','DODGER'),('league.inc','LEAGUE'),('chocobo.inc','CHOCO'),
         ('blitzlvl.inc','BLITZLVL'),('blitzlearn.inc','BLITZLEARN'))

def assemble(inc, symvals):
    d = tempfile.mkdtemp()
    src = '.intel_syntax noprefix\n' + ''.join('.set %s, 0x%X\n'%(k,v) for k,v in symvals.items()) + \
          '.text\n.include "%s"\n' % os.path.join(ROOT,'caves',inc)
    open(d+'/a.s','w').write(src)
    subprocess.check_call(['as','--32','-o',d+'/a.o',d+'/a.s'])
    subprocess.check_call(['objcopy','-O','binary','-j','.text',d+'/a.o',d+'/a.bin'])
    return open(d+'/a.bin','rb').read(), d+'/a.o'

def relocs(code):
    out=[]
    for name,val in PLACEHOLDERS.items():
        pat=struct.pack('<I',val); i=0
        while True:
            i=code.find(pat,i)
            if i<0: break
            out.append((i,WHICH.index(name))); i+=1
    return sorted(out)

def carr(name, b):
    lines=[', '.join('0x%02X'%x for x in b[i:i+12]) for i in range(0,len(b),12)]
    return 'static const hk_u8 %s[%d] = {\n    %s\n};\n' % (name,len(b),',\n    '.join(lines))

if __name__=='__main__':
    h  = '/* caves.h - GENERATED by tools/gen_caves.py from the caves folder with GNU as. Do not edit. */\n'
    h += '#ifndef CAVES_H\n#define CAVES_H\n#include "hookutil.h"\n\n'
    h += '/* relocation: the dword at byte offset `pos` holds a placeholder for data item `which`. */\n'
    h += 'enum { ' + ', '.join('RELOC_'+w[2:] for w in WHICH) + ', RELOC_COUNT };\n\n'
    for inc,nm in CAVES:
        code,_=assemble(inc,PLACEHOLDERS); rl=relocs(code)
        h += carr('CAVE_%s'%nm, code)
        h += 'static const HkReloc CAVE_%s_RELOCS[%d] = { %s };\n' % (nm,len(rl),', '.join('{%d,%d}'%r for r in rl))
        h += '#define CAVE_%s_LEN %d\n#define CAVE_%s_NRELOCS %d\n\n' % (nm,len(code),nm,len(rl))
        print('%-10s cave: %3d bytes, %2d relocations' % (nm,len(code),len(rl)))
    h += '#endif\n'
    open(os.path.join(ROOT,'caves.h'),'w').write(h)
